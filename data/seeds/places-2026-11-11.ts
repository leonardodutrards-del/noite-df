const checkedAt = '2026-11-11';

type DraftInput = Pick<Establishment, 'id' | 'name' | 'region' | 'type' | 'description' | 'address' | 'mapsQuery'> & {
  phone?: string;
  hours?: string;
  rating?: number;
  reviewCount?: number;
  vibe?: string[];
  music?: string[];
  instagram?: string;
  menuUrl?: string;
  source?: Establishment['source'];
};

const mapsUrl = (name: string, address: string) =>
  `https://www.google.com/maps/search/?api=1&query=${encodeURIComponent(`${name}, ${address}`)}`;

const draft = (input: DraftInput): Establishment => {
  const mapUrl = mapsUrl(input.name, input.address);
  return {
    id: input.id,
    name: input.name,
    region: input.region,
    type: input.type,
    description: input.description,
    address: input.address,
    vibe: input.vibe ?? [],
    music: input.music ?? [],
    audience: [],
    ...(input.instagram ? { instagram: input.instagram } : {}),
    ...(input.phone ? {
      businessContact: {
        phone: input.phone,
        sourceUrl: mapUrl,
        checkedAt,
      },
    } : {}),
    ...(input.hours ? {
      operatingHours: {
        text: input.hours,
        sourceUrl: mapUrl,
        checkedAt,
      },
    } : {}),
    ...(input.menuUrl ? {
      menu: {
        url: input.menuUrl,
        checkedAt,
        images: [],
        examples: [],
      },
    } : {}),
    mapsQuery: input.mapsQuery,
    verified: false,
    ownerManaged: false,
    crowdStatus: 'a confirmar',
    weeklySchedule: [],
    lastUpdated: checkedAt,
    publicationStatus: 'draft',
    source: input.source ?? {
      kind: 'external',
      label: 'Google Business — listing público localizado por nome e endereço; confirmação direta com o estabelecimento pendente.',
      url: mapUrl,
      verifiedAt: checkedAt,
    },
    publicRatings: input.rating ? [{
      provider: 'google',
      label: 'Google Business',
      url: mapUrl,
      rating: input.rating,
      reviewCount: input.reviewCount,
      collectedAt: checkedAt,
      matchedBy: ['nome', 'endereço'],
      status: 'needs_review',
      observation: 'Nota e volume de avaliações copiados do perfil público; correspondência e exibição aguardam revisão manual.',
    }] : [],
    publicRatingSummary: { sourceCount: 0, calculatedAt: checkedAt },
  };
};

